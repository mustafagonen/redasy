export function localizedPage(page: SitePage, locale: Locale): SitePage {
  if (locale === "tr") return page;
  const pack = pages[page.slug];
  if (!pack) return page;
  return {
    ...page,
    title: pack.title[locale] || page.title,
    lead: pack.lead[locale] || page.lead,
    sections: page.sections.map((section) => {
      const row = pack.sections[section.id];
      if (!row) return section;
      return { ...section, title: row.title[locale] || section.title, text: row.text[locale] || section.text };
    }),
  };
}

